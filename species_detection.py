from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

pipe=make_pipeline(StandardScaler(),LogisticRegression())
X, y=load_iris(return_X_y=True)
df=pd.DataFrame(X,columns=['sepal_length','sepal_width','petal_length','petal_width'])
df.head()

df1=pd.DataFrame(y,columns=['species'])
df1.tail()
df1.describe()

X_trian,X_test,y_train,y_test=train_test_split(X,y,random_state=0)
pipe.fit(X_trian,y_train)

accuracy_score(pipe.predict(X_test),y_test)

plt.figure(figsize=(10, 6))
plt.scatter(range(len(y_test)), y_test, color='green', label='Actual (y_test)')
plt.plot(range(len(y_test)), pipe.predict(X_test), color='red', label='Predicted (pipe.predict(X_test))')
plt.xlabel('Number of species')
plt.ylabel('Species')
plt.title('Actual vs. Predicted Species')
plt.legend()
plt.show()